import type { VercelRequest, VercelResponse } from '@vercel/node';
import { parseCookies, verifySessionToken } from './_helpers.js';

function safeJson(value: unknown) {
  return JSON.stringify(value, null, 2)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026');
}

function generatedFile(config: any) {
  const brandData = config?.brandData ?? {};
  const editorConfig = config?.editorConfig ?? {};
  const publishedAt =
    typeof config?.publishedAt === 'string'
      ? config.publishedAt
      : new Date().toISOString();

  return `// AUTO-GENERATED BY THE SITE VISUAL EDITOR.
// Do not edit manually: the next publication will overwrite this file.

export const publishedSiteContent = ${safeJson({
    brandData,
    editorConfig,
    publishedAt,
  })} as const;
`;
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  if (req.method !== 'PUT') {
    return res.status(405).json({ success: false, error: 'Method not allowed' });
  }

  // Publication réservée à une vraie session administrateur signée.
  // On utilise exactement le même mécanisme que /api/site-config.
  const session = verifySessionToken(
    parseCookies(req.headers.cookie).admin_session
  );

  if (!session.valid) {
    return res.status(401).json({ success: false, error: 'Non autorisé' });
  }

  const token = process.env.GITHUB_TOKEN;
  const repository = process.env.GITHUB_REPOSITORY;
  const branch = process.env.GITHUB_BRANCH || 'main';
  const filePath =
    process.env.GITHUB_PUBLISHED_FILE ||
    'src/data/site-content.generated.ts';

  if (!token || !repository) {
    return res.status(503).json({
      success: false,
      error: 'GITHUB_TOKEN ou GITHUB_REPOSITORY manque dans Vercel.',
    });
  }

  const body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
  const config = body?.config;

  if (!config || typeof config !== 'object') {
    return res.status(400).json({
      success: false,
      error: 'config est obligatoire.',
    });
  }

  const [owner, repo] = repository.split('/');
  if (!owner || !repo) {
    return res.status(500).json({
      success: false,
      error: 'GITHUB_REPOSITORY doit être owner/repository.',
    });
  }

  const apiUrl = `https://api.github.com/repos/${owner}/${repo}/contents/${filePath}`;

  const headers = {
    Accept: 'application/vnd.github+json',
    Authorization: `Bearer ${token}`,
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type': 'application/json',
    'User-Agent': 'Site-Internet-Benoit-V14',
  };

  try {
    const content = generatedFile(config);
    const encoded = Buffer.from(content, 'utf8').toString('base64');

    const readCurrent = async () => {
      const existing = await fetch(
        `${apiUrl}?ref=${encodeURIComponent(branch)}`,
        { headers }
      );

      if (existing.ok) {
        return await existing.json();
      }

      if (existing.status === 404) return null;

      const text = await existing.text();
      throw new Error(
        `Lecture GitHub impossible (${existing.status}): ${text.slice(0, 300)}`
      );
    };

    const updateOnce = async (sha?: string) => {
      const payload: Record<string, unknown> = {
        message: 'chore(site-editor): publish visual site changes',
        content: encoded,
        branch,
      };

      if (sha) payload.sha = sha;

      return fetch(apiUrl, {
        method: 'PUT',
        headers,
        body: JSON.stringify(payload),
      });
    };

    let existingData = await readCurrent();

    // Ne crée pas un commit si le contenu est déjà exactement celui demandé.
    // Cela évite une rafale de commits identiques depuis l'espace admin.
    if (existingData?.content) {
      try {
        const currentContent = Buffer.from(
          String(existingData.content).replace(/\s+/g, ''),
          'base64'
        ).toString('utf8');

        if (currentContent === content) {
          return res.status(200).json({
            success: true,
            commitSha: null,
            unchanged: true,
            path: filePath,
            branch,
          });
        }
      } catch {
        // Si GitHub renvoie un contenu inattendu, on poursuit avec la mise à jour.
      }
    }

    let update = await updateOnce(existingData?.sha);

    // Une autre publication peut avoir changé le SHA entre la lecture et l'écriture.
    // On relit une seule fois et on réessaie avec le dernier SHA plutôt que de
    // perdre silencieusement la dernière modification.
    if (update.status === 409) {
      existingData = await readCurrent();
      update = await updateOnce(existingData?.sha);
    }

    const result = await update.json().catch(() => ({}));

    if (!update.ok) {
      return res.status(502).json({
        success: false,
        error:
          result?.message ||
          `GitHub a refusé la publication (${update.status}).`,
      });
    }

    return res
      .status(200)
      .setHeader(
        'Cache-Control',
        'no-store, no-cache, must-revalidate, proxy-revalidate, max-age=0'
      )
      .json({
        success: true,
        commitSha: result?.commit?.sha || null,
        path: filePath,
        branch,
      });
  } catch (error) {
    console.error('site-publish:', error);
    return res.status(500).json({
      success: false,
      error: 'Erreur pendant la publication GitHub.',
    });
  }
}
